const page=await browser.newPage({viewport:{width:375,height:812},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
const user={id:'test-only',username:'verifica',displayName:'Verifica locale',avatar:null,profileCompleted:true,bio:'',hue:1,sports:['running'],area:'',privacy:{showStats:true,showClubs:true,showUpcoming:true,shareActivity:false},createdAt:new Date().toISOString(),setup:null};
